-- SEC-10: госномер уникален в пределах компании, а не на всю платформу.
-- Раньше любая компания могла внести чужой номер и тем самым не дать владельцу машины добавить её.
-- Теперь номер может быть у нескольких компаний (совпадение фиксируется в журнале аудита для администратора),
-- но внутри одной компании — только у одной неудалённой машины. Данные не меняются: прежнее ограничение было строже.

DROP INDEX "Vehicle_active_plate_unique";

CREATE UNIQUE INDEX "Vehicle_company_plate_unique" ON "Vehicle" ("companyId", "country", "plateNumber")
  WHERE "deletedAt" IS NULL;
